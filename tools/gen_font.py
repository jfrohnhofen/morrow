#!/usr/bin/env python3
"""Regenerate firmware/src/font.rs from the Spleen 5x8 BDF.

The clock screens use the glyphs in `bitmaps.rs`; this font exists only for the
text setup mode has to show, which the original firmware never needed.

Spleen is BSD-2-Clause, (c) Frederic Cambus. Point FONT_BDF at a copy, or run
inside the dev shell where nixpkgs provides one.

Usage:  python3 tools/gen_font.py [path/to/spleen-5x8.bdf]
"""
import re
import subprocess
import sys

OUT = "firmware/src/font.rs"
W, H = 5, 8


def find_bdf():
    if len(sys.argv) > 1:
        return sys.argv[1]
    out = subprocess.run(
        ["nix", "build", "--no-link", "--print-out-paths", "nixpkgs#spleen"],
        capture_output=True, text=True, check=True).stdout.strip()
    return f"{out}/share/fonts/misc/spleen-5x8.bdf"


def main():
    txt = open(find_bdf()).read()
    glyphs = {}
    for blk in txt.split("STARTCHAR")[1:]:
        enc = re.search(r"^ENCODING\s+(-?\d+)", blk, re.M)
        bbx = re.search(r"^BBX\s+(\d+)\s+(\d+)", blk, re.M)
        bm = re.search(r"^BITMAP\s*\n(.*?)^ENDCHAR", blk, re.M | re.S)
        if not (enc and bbx and bm):
            continue
        cp = int(enc.group(1))
        if not 0x20 <= cp <= 0x7E:
            continue
        w = int(bbx.group(1))
        rows = [int(l.strip(), 16) for l in bm.group(1).split() if l.strip()]
        pad = (w + 7) // 8 * 8
        glyphs[cp] = [[(r >> (pad - 1 - x)) & 1 for x in range(w)] for r in rows]

    assert len(glyphs) == 95, len(glyphs)
    rows_out = []
    for cp in range(0x20, 0x7F):
        px = glyphs[cp]
        cols = [
            sum(1 << y for y in range(H)
                if y < len(px) and x < len(px[y]) and px[y][x])
            for x in range(W)
        ]
        label = {"\\": "\\\\", "'": "\\'"}.get(chr(cp), chr(cp))
        rows_out.append(
            f"    [{', '.join(f'0x{c:02x}' for c in cols)}], // {cp:#04x} '{label}'")

    open(OUT, "w").write(f'''//! A 5x8 bitmap font for the setup screen.
//!
//! Generated by `tools/gen_font.py` from Spleen 5x8 (BSD-2-Clause, Frederic
//! Cambus). Do not edit by hand.
//!
//! The clock and alarm screens use the glyphs in [`crate::bitmaps`] instead;
//! this font exists for the text that setup mode has to show, which the
//! original firmware never needed.
//!
//! Packed column-major, one byte per column with bit 0 topmost, so a glyph can
//! be drawn with the same inner loop as everything else.

/// Glyph height in pixels.
pub const FONT_H: i32 = {H};

/// Pixel advance between glyph origins.
///
/// Equal to the glyph box width: Spleen 5x8 draws into four columns and leaves
/// the fifth blank, so the box already carries its own tracking.
pub const FONT_ADVANCE: i32 = {W};

/// Glyphs for printable ASCII, indexed by codepoint minus 0x20.
static GLYPHS: [[u8; {W}]; {len(rows_out)}] = [
{chr(10).join(rows_out)}
];

/// Returns the glyph columns for `c`, substituting `?` outside printable ASCII.
pub fn glyph(c: char) -> &'static [u8; {W}] {{
    let i = (c as u32).wrapping_sub(0x20) as usize;
    match GLYPHS.get(i) {{
        Some(g) => g,
        None => &GLYPHS[(b'?' - 0x20) as usize],
    }}
}}

/// Width in pixels of `s` rendered in this font, excluding trailing tracking.
pub fn text_width(s: &str) -> i32 {{
    let n = s.chars().count() as i32;
    if n == 0 {{ 0 }} else {{ n * FONT_ADVANCE - 1 }}
}}
''')
    print(f"wrote {OUT}: {len(rows_out)} glyphs, {W}x{H}")


if __name__ == "__main__":
    main()
