#!/usr/bin/env python3
"""Regenerate ui/src/digits.rs from the original MicroPython bitmaps.

The panel is driven with SEG_REMAP set (0xA1), which mirrors it horizontally in
hardware, and it is mounted rotated. The two together come out as a plain
transpose of buffer space, which is what this applies so the web UI shows the
same numerals the right way up. Verified against the TIME/ALARM/WEEKDAYS word
bitmaps, which only read correctly under this transform.

Usage:  python3 tools/gen_web_digits.py
"""
import ast
import re

SRC = "sunrise-alarm/main.py"
OUT = "ui/src/digits.rs"
W, H = 14, 8


def digits():
    src = open(SRC).read()
    body = re.search(r"DIGITS = \[(.*?)\n\]\n", src, re.S).group(1)
    return [ast.literal_eval(e) for e in re.findall(r'bytearray\((b"[^"]*")\)', body)]


def unpack_vlsb(data):
    px = [[0] * W for _ in range(H)]
    for page in range((H + 7) // 8):
        for x in range(W):
            byte = data[page * W + x]
            for bit in range(8):
                y = page * 8 + bit
                if y < H:
                    px[y][x] = (byte >> bit) & 1
    return px


def main():
    rows = []
    for i, d in enumerate(digits()):
        px = unpack_vlsb(d)
        upright = [[px[y][x] for y in range(H)] for x in range(W)]
        words = [sum(0x80 >> x for x, b in enumerate(r) if b) for r in upright]
        art = "\n".join(
            "    //      " + "".join("#" if (w >> (7 - x)) & 1 else "." for x in range(8))
            for w in words
        )
        rows.append(f"    // {i}\n{art}\n    [{', '.join(f'0x{w:02x}' for w in words)}],")

    open(OUT, "w").write(f'''//! The clock digits from the OLED, upright, for rendering in HTML.
//!
//! Generated by `tools/gen_web_digits.py` from the same `main.py` bitmaps the
//! firmware draws. Do not edit by hand.
//!
//! The stored glyphs look sideways and mirrored because the panel runs with
//! SEG_REMAP set and is mounted rotated; the two cancel out to a transpose,
//! which is applied here. Using the device's own digits is what makes the two
//! interfaces look like one product.

/// Glyph width in pixels.
pub const DIGIT_W: usize = 8;

/// Glyph height in pixels.
pub const DIGIT_H: usize = 14;

/// The ten digits, indexed by value: one byte per row, bit 7 leftmost.
pub static DIGITS: [[u8; DIGIT_H]; 10] = [
{chr(10).join(rows)}
];
''')
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
