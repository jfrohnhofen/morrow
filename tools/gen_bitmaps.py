#!/usr/bin/env python3
"""Regenerate firmware/src/bitmaps.rs from the original MicroPython firmware.

Transcribing these by hand would be a reliable way to introduce a one-bit
difference nobody notices until the display looks subtly wrong, so they are
extracted from `main.py` and `leds.py` instead.

Usage:  python3 tools/gen_bitmaps.py
"""
import ast
import re

MAIN = "sunrise-alarm/main.py"
LEDS = "sunrise-alarm/leds.py"
OUT = "firmware/src/bitmaps.rs"

LABELS = [
    ("TIME", 'The word "TIME", drawn beside the current-time readout.'),
    ("ALARM", 'The word "ALARM", drawn beside the alarm readout.'),
    ("OFF", 'The word "OFF", shown in place of an alarm time when disabled.'),
    ("EVERY_DAY", 'The words "EVERY DAY", the daily recurrence label.'),
    ("WEEKDAYS", 'The word "WEEKDAYS", the Mon-Fri recurrence label.'),
    ("WEEKENDS", 'The word "WEEKENDS", the Sat-Sun recurrence label.'),
]

HEADER = '''//! Bitmaps lifted verbatim from the MicroPython firmware.
//!
//! Generated by `tools/gen_bitmaps.py` from the original `main.py` and
//! `leds.py` so the glyphs are bit-identical to what the old firmware drew. Do
//! not edit by hand.
//!
//! Two pixel layouts are in play, matching MicroPython's `framebuf`:
//!
//! * [`Fmt::Vlsb`] — one byte per 8-pixel-tall column strip, LSB topmost.
//! * [`Fmt::Hlsb`] — one byte per 8-pixel-wide row run, MSB leftmost.
//!
//! The panel runs with SEG_REMAP set and is mounted rotated, so these glyphs
//! read sideways and mirrored in buffer space. That is deliberate: the two
//! transforms cancel on the physical panel.

/// Pixel packing of a [`Bitmap`], mirroring MicroPython's `framebuf` modes.
#[derive(Copy, Clone, PartialEq, Eq)]
pub enum Fmt {
    /// Vertical strips, least-significant bit at the top.
    Vlsb,
    /// Horizontal runs, most-significant bit on the left.
    Hlsb,
}

/// A 1-bit image with the geometry the original firmware blitted it at.
pub struct Bitmap {
    /// Packed pixel data.
    pub data: &'static [u8],
    /// Width in pixels.
    pub w: i32,
    /// Height in pixels.
    pub h: i32,
    /// How `data` is packed.
    pub fmt: Fmt,
}

impl Bitmap {
    /// Returns the pixel at `(x, y)`, or `false` outside the bitmap.
    pub fn pixel(&self, x: i32, y: i32) -> bool {
        if x < 0 || y < 0 || x >= self.w || y >= self.h {
            return false;
        }
        let (idx, bit) = match self.fmt {
            Fmt::Vlsb => ((y / 8) * self.w + x, y % 8),
            Fmt::Hlsb => {
                // div_ceil is unstable for signed integers.
                let stride = (self.w + 7) / 8;
                (y * stride + x / 8, 7 - (x % 8))
            }
        };
        match self.data.get(idx as usize) {
            Some(byte) => (byte >> bit) & 1 == 1,
            None => false,
        }
    }
}
'''


def framebuf(src, name):
    m = re.search(
        rf"^{name} = framebuf\.FrameBuffer\(\s*bytearray\((.*?)\),\s*(\d+),\s*(\d+),"
        r"\s*framebuf\.(MONO_\w+),",
        src, re.S | re.M)
    if not m:
        raise SystemExit(f"not found: {name}")
    blob = b"".join(ast.literal_eval(p.strip()) for p in re.findall(r'b"[^"]*"', m.group(1)))
    return blob, int(m.group(2)), int(m.group(3)), m.group(4)


def rust_bytes(b, per=16):
    return ",\n    ".join(
        ", ".join(f"0x{x:02x}" for x in b[i:i + per]) for i in range(0, len(b), per))


def main():
    src = open(MAIN).read()
    leds = open(LEDS).read()
    parts = [HEADER]

    for name, doc in LABELS:
        blob, w, h, fmt = framebuf(src, name)
        rf = "Fmt::Vlsb" if fmt == "MONO_VLSB" else "Fmt::Hlsb"
        parts.append(f"""/// {doc}
pub static {name}: Bitmap = Bitmap {{
    data: &[
    {rust_bytes(blob)},
    ],
    w: {w},
    h: {h},
    fmt: {rf},
}};
""")

    body = re.search(r"DIGITS = \[(.*?)\n\]\n", src, re.S).group(1)
    digits = [ast.literal_eval(e) for e in re.findall(r'bytearray\((b"[^"]*")\)', body)]
    assert len(digits) == 10 and all(len(d) == 14 for d in digits)
    rows = ",\n".join(
        f"""    // {i}
    Bitmap {{
        data: &[{', '.join(f'0x{x:02x}' for x in d)}],
        w: 14,
        h: 8,
        fmt: Fmt::Vlsb,
    }}""" for i, d in enumerate(digits))
    parts.append(f"""/// The ten clock digits, indexed by value.
pub static DIGITS: [Bitmap; 10] = [
{rows},
];
""")

    order = ast.literal_eval("[" + re.search(r"LED_ORDER = \[(.*?)\n\]", leds, re.S).group(1) + "]")
    assert sorted(order) == list(range(len(order)))
    table = ",\n    ".join(
        ", ".join(str(v) for v in order[i:i + 16]) for i in range(0, len(order), 16))
    parts.append(f"""/// Number of WS2812 pixels on the strip.
pub const LED_COUNT: usize = {len(order)};

/// Order in which pixels receive the dither increment.
///
/// A fixed pseudo-random permutation of `0..LED_COUNT`. Spreading the low byte
/// of the 16-bit brightness across the strip in a scattered order is what makes
/// the very bottom of the ramp look smooth instead of banded, so the exact
/// permutation is carried over unchanged from the MicroPython firmware.
pub static LED_ORDER: [u16; LED_COUNT] = [
    {table},
];
""")

    open(OUT, "w").write("\n".join(parts))
    print(f"wrote {OUT}: {len(LABELS)} labels, 10 digits, LED_COUNT={len(order)}")


if __name__ == "__main__":
    main()
